// Regenerates lib/abi.ts from Foundry's out/. Run after `forge build`.
import { readFileSync, writeFileSync } from 'node:fs';

const out = new URL('../../contracts/out/', import.meta.url);
const abi = (name) => JSON.stringify(JSON.parse(readFileSync(new URL(`${name}.sol/${name}.json`, out))).abi, null, 2);
writeFileSync(
  new URL('../lib/abi.ts', import.meta.url),
  `// Generated by scripts/gen-abi.mjs from contracts/out. Do not edit.\n` +
    `export const cuanLaterAbi = ${abi('CuanLater')} as const;\n\n` +
    `export const mockUsdAbi = ${abi('MockUSD')} as const;\n`,
);
console.log('wrote lib/abi.ts');
